function [T, q, x, z, largestError] = check_prescribed_path( ...
        A, b, c, bases, expectedTableaus, expectedIndicators, ...
        expectedPoints, expectedValues, prescribedPivots, tol)
% Verification of supplied data only: no automatic optimization or pivot search.
    count = size(bases, 1);
    assert(numel(expectedTableaus) == count);
    assert(size(prescribedPivots, 1) == count - 1);
    largestError = 0;
    for k = 1:count
        B = bases(k, :);
        assert(numel(unique(B)) == size(A, 1));
        assert(rank(A(:, B)) == size(A, 1));
        T = A(:, B) \ [A, b];
        rhs = T(:, end);
        q = T(:, 1:end-1)' * c(B) - c;
        x = zeros(size(A, 2), 1);
        x(B) = rhs;
        z = c' * x;
        assert(all(rhs >= -tol) && all(x >= -tol));
        assert(norm(T(:, B) - eye(size(A, 1)), Inf) <= tol);
        assert(norm(q(B), Inf) <= tol);
        differences = [reshape(T - expectedTableaus{k}, [], 1); ...
            q - expectedIndicators(k, :)'; x - expectedPoints(k, :)'; ...
            z - expectedValues(k); A*x - b];
        largestError = max(largestError, max(abs(differences)));
        assert(max(abs(differences)) <= tol);
        if k == count
            continue;
        end
        enter = prescribedPivots(k, 1);
        leave = prescribedPivots(k, 2);
        step = prescribedPivots(k, 3);
        assert(~ismember(enter, B));
        r = find(B == leave);
        assert(isscalar(r));
        assert(T(r, enter) > tol && step > tol);
        eligible = T(:, enter) > tol;
        ratios = rhs(eligible) ./ T(eligible, enter);
        assert(abs(step - min(ratios)) <= tol);
        assert(abs(step - rhs(r) / T(r, enter)) <= tol);
        assert(q(enter) <= tol); % Includes the documented zero-cost alternative pivots.
        if q(enter) < -tol
            N = setdiff(1:size(A, 2), B);
            assert(abs(q(enter) - min(q(N))) <= tol);
        else
            assert(all(q >= -tol));
        end
        nextB = B;
        nextB(r) = enter;
        assert(isequal(nextB, bases(k+1, :)));
        normalizedRow = T(r, :) / T(r, enter);
        pivoted = T;
        for i = 1:size(A, 1)
            if i == r
                pivoted(i, :) = normalizedRow;
            else
                pivoted(i, :) = T(i, :) - T(i, enter) * normalizedRow;
            end
        end
        nextT = A(:, nextB) \ [A, b];
        assert(norm(pivoted - nextT, Inf) <= tol);
        direction = zeros(size(A, 2), 1);
        direction(enter) = 1;
        direction(B) = -T(:, enter);
        nextX = x + step * direction;
        assert(all(nextX >= -tol));
        assert(norm(nextX - expectedPoints(k+1, :)', Inf) <= tol);
        assert(abs(c' * nextX - (z - q(enter) * step)) <= tol);
        assert(abs(c' * nextX - expectedValues(k+1)) <= tol);
        if abs(q(enter)) <= tol
            assert(norm(nextX(1:3) - x(1:3), Inf) > tol);
        end
    end
end

function check_growth_ray(A, b, c, T, q, x, enter, expectedDirection, slope, tol)
% Check the explicit mathematical certificate rather than merely a failed ratio.
    assert(q(enter) < -tol && all(T(:, enter) <= tol));
    assert(norm(A * expectedDirection, Inf) <= tol);
    assert(all(expectedDirection >= -tol));
    assert(abs(expectedDirection(enter) - 1) <= tol);
    assert(norm(T(:, 1:end-1) * expectedDirection, Inf) <= tol);
    assert(abs(c' * expectedDirection - slope) <= tol && slope > 0);
    assert(abs(slope + q(enter)) <= tol);
    assert(norm(A * x - b, Inf) <= tol && all(x >= -tol));
    % The matrix and sign identities hold for every theta >= 0; these are samples.
    for theta = [0, 1, 100]
        candidate = x + theta * expectedDirection;
        assert(all(candidate >= -tol));
        assert(norm(A * candidate - b, Inf) <= tol);
        assert(abs(c' * candidate - (c' * x + theta * slope)) <= tol);
    end
end
